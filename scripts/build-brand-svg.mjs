/**
 * Generates lib/brand-svg.ts from the monochrome brand SVGs in public/brand.
 *
 * The source files are authored for a dark navy ground: the wordmark is white
 * with an orange accent, and the client marks are a flat #A3B8D4. Dropped onto
 * a light page as-is, the white and the pale blue both disappear.
 *
 * This rewrites the single flat colour in each file to `currentColor` so the
 * mark inherits whatever token the surrounding element sets, then inlines the
 * markup into a TS module. Inlining (rather than reading the file at runtime)
 * keeps the marks usable from Client Components and costs no extra request.
 *
 * Re-run after replacing any file in public/brand:  node scripts/build-brand-svg.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(process.cwd(), "public", "brand");

// file -> the flat colour in that file that should follow the page token
const MONOCHROME = {
  "clients/paypal.svg": "#A3B8D4",
  "clients/kotak.svg": "#A3B8D4",
  "clients/adani.svg": "#A3B8D4",
  "clients/capita.svg": "#A3B8D4",
  "clients/ssp.svg": "#A3B8D4",
  "clients/dssmith.svg": "#A3B8D4",
  "clients/payu.svg": "#A3B8D4",
  "clients/mankind.svg": "#A3B8D4",
  "clients/fino.svg": "#A3B8D4",
  "clients/avendus.svg": "#A3B8D4",
  "clients/godrej.svg": "#A3B8D4",
  "clients/larsen-toubro.svg": "#A3B8D4",
  "clients/tui.svg": "#A3B8D4",
  "clients/convatec.svg": "#A3B8D4",
  "clients/jefferson-health.svg": "#A3B8D4",
  "clients/nyu-langone.svg": "#A3B8D4",
  "clients/emory.svg": "#A3B8D4",
  "clients/agd-bank.svg": "#A3B8D4",
  "clients/xanadu.svg": "#A3B8D4",
  "clients/centrum.svg": "#A3B8D4",
  "clients/bsv.svg": "#A3B8D4",
  "clients/the-in-group.svg": "#A3B8D4",
  // Pidilite's real mark (Wikimedia Commons) is multi-colour (a navy
  // wordmark, a yellow sun, a blue gradient wave) pre-flattened to this one
  // placeholder so it recolours the same way every other client mark does,
  // rather than carrying its own colours into a page where every other
  // logo is monochrome. Uses #A3B8D4 rather than black: svgo treats a flat
  // #000000 fill as SVG's own implicit default and strips the attribute
  // entirely, which silently breaks the exact-string replace below.
  "clients/pidilite.svg": "#A3B8D4",
};

function prepare(file, flat) {
  let svg = readFileSync(join(ROOT, file), "utf8").trim();
  svg = svg.replace(/<\?xml[^>]*\?>/g, "").replace(/<!--[\s\S]*?-->/g, "");
  // The flat brand colour becomes the inherited text colour.
  if (flat === "white") {
    svg = svg.replace(/fill="white"/gi, 'fill="currentColor"');
    svg = svg.replace(/stroke="white"/gi, 'stroke="currentColor"');
  } else {
    const re = new RegExp(flat.replace("#", "#"), "gi");
    svg = svg.replace(re, "currentColor");
  }
  // Drop intrinsic sizing so CSS controls it; viewBox stays.
  svg = svg.replace(/\s(width|height)="[^"]*"/g, "");
  // These marks are decorative next to a text label, or labelled by the parent.
  svg = svg.replace(/<svg/, '<svg focusable="false" aria-hidden="true"');
  return svg.replace(/\s+/g, " ").trim();
}

const entries = Object.entries(MONOCHROME).map(([file, flat]) => {
  const key = file
    .replace(/\.svg$/, "")
    .replace(/[\/-](.)/g, (_, c) => c.toUpperCase());
  return `  ${key}: ${JSON.stringify(prepare(file, flat))},`;
});

const out = `/**
 * GENERATED by scripts/build-brand-svg.mjs. Do not edit by hand.
 *
 * Brand marks with their flat colour rewritten to \`currentColor\`, so each one
 * takes the colour of the element it is rendered into and therefore works in
 * both themes. Re-run the script after changing anything in public/brand.
 */
export const brandSvg = {
${entries.join("\n")}
} as const;

export type BrandSvgKey = keyof typeof brandSvg;
`;

writeFileSync(join(process.cwd(), "lib", "brand-svg.ts"), out);
console.log(`wrote lib/brand-svg.ts with ${entries.length} marks`);

/**
 * The wordmark is 14KB of outlined paths and renders three times per page
 * (header, mobile drawer, footer). Inlining it would put 42KB of duplicated
 * path data in every document, so it ships as two cached files instead: the
 * source white-on-dark version, and an ink-coloured copy for the light theme.
 * The orange accent is untouched in both.
 */
// logo.svg is the source file and is not committed; the two outputs are. Skip
// rather than fail so the client marks can be regenerated on their own.
if (existsSync(join(ROOT, "logo.svg"))) {
  const wordmark = readFileSync(join(ROOT, "logo.svg"), "utf8").trim();
  writeFileSync(join(ROOT, "logo-dark.svg"), wordmark);
  writeFileSync(
    join(ROOT, "logo-light.svg"),
    wordmark.replace(/fill="white"/gi, 'fill="#0a1327"'),
  );
  console.log("wrote public/brand/logo-light.svg and logo-dark.svg");
}
